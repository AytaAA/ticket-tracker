"""Create demo/test tickets through the API (§8.10, DoD-10). Never used on startup: no seed data (§9.9).

Uses an existing, verified account. The password is asked for interactively (or read from TT_PASSWORD),
so it never ends up in shell history or in the repo.

    python scripts/bulk_tickets.py --email you@example.com --team "Load Test" --count 150

Standard library only; works with Python 3.10+ on Windows, WSL or macOS.
"""

import argparse
import getpass
import http.cookiejar
import json
import os
import random
import sys
import urllib.error
import urllib.request

TYPES = ["bug", "feature", "fix"]
STATES = ["new", "ready_for_implementation", "in_progress", "ready_for_acceptance", "done"]
EPICS = ["Checkout reliability", "Payments v2", "Fraud detection"]
WORDS = ["payment", "login", "checkout", "refund", "invoice", "export", "search", "profile", "cart", "webhook"]
PROBLEMS = ["fails", "is slow", "shows wrong total", "times out", "needs retry", "misaligned", "returns 500"]


class Api:
    def __init__(self, base_url: str):
        self.base = base_url.rstrip("/") + "/api"
        self.opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))

    def call(self, method: str, path: str, body: dict | None = None):
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(self.base + path, data=data, method=method)
        if data is not None:
            req.add_header("Content-Type", "application/json")
        try:
            with self.opener.open(req, timeout=30) as resp:
                raw = resp.read()
                return json.loads(raw) if raw else None
        except urllib.error.HTTPError as e:
            detail = e.read().decode(errors="replace")
            raise SystemExit(f"{method} {path} -> HTTP {e.code}: {detail}") from None
        except urllib.error.URLError as e:
            raise SystemExit(f"Cannot reach {self.base}: {e.reason}. Is the stack running?") from None


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--base-url", default="http://localhost:8080")
    p.add_argument("--email", required=True, help="an existing, verified account")
    p.add_argument("--team", default="Load Test", help="team name; created if it does not exist")
    p.add_argument("--count", type=int, default=150)
    p.add_argument("--seed", type=int, default=None, help="random seed for repeatable data")
    args = p.parse_args()

    password = os.environ.get("TT_PASSWORD") or getpass.getpass(f"Password for {args.email}: ")
    rnd = random.Random(args.seed)
    api = Api(args.base_url)
    api.call("POST", "/auth/login", {"email": args.email, "password": password})

    team = next((t for t in api.call("GET", "/teams") if t["name"].lower() == args.team.strip().lower()), None)
    if team is None:
        team = api.call("POST", "/teams", {"name": args.team})
        print(f"Created team '{team['name']}' (id {team['id']})")
    else:
        print(f"Using existing team '{team['name']}' (id {team['id']})")

    existing = {e["title"]: e for e in api.call("GET", f"/epics?team_id={team['id']}")}
    epics = [existing.get(t) or api.call("POST", "/epics", {"team_id": team["id"], "title": t}) for t in EPICS]

    for i in range(1, args.count + 1):
        epic = rnd.choice(epics + [None])
        api.call("POST", "/tickets", {
            "team_id": team["id"],
            "type": rnd.choice(TYPES),
            "state": rnd.choice(STATES),
            "epic_id": epic["id"] if epic else None,
            "title": f"{rnd.choice(WORDS).capitalize()} {rnd.choice(PROBLEMS)} #{i}",
            "body": f"Generated by scripts/bulk_tickets.py (ticket {i} of {args.count}).",
        })
        if i % 25 == 0 or i == args.count:
            print(f"  {i}/{args.count} tickets created")

    print(f"Done. Open {args.base_url}/board?team={team['id']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
